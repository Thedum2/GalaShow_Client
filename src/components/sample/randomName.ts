export function makeRandomName(sep : string) {
    const prefixes = NAME_PREFIXES;
    const suffixes = NAME_SUFFIXES;

    if (!Array.isArray(prefixes) || prefixes.length === 0) {
        throw new Error("prefixes 리스트가 비어있습니다.");
    }
    if (!Array.isArray(suffixes) || suffixes.length === 0) {
        throw new Error("suffixes 리스트가 비어있습니다.");
    }

    const p = prefixes[Math.floor(Math.random() * prefixes.length)];
    const s = suffixes[Math.floor(Math.random() * suffixes.length)];
    return `${p}${sep}${s}`;
}

